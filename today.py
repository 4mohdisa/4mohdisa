def gql(query, variables, token, tries=4):
    for attempt in range(tries):
        r = requests.post(
            API,
            json={"query": query, "variables": variables},
            headers={"Authorization": f"bearer {token}"},
            timeout=60,
        )
        if r.status_code == 200 and "errors" not in r.json():
            return r.json()["data"]
        if attempt == tries - 1:
            raise RuntimeError(f"GitHub API failed: {r.status_code} {r.text[:400]}")
        time.sleep(2 ** attempt)


def fetch_profile(token):
    q = """
    query($login:String!){
      user(login:$login){
        id createdAt
        followers{totalCount}
        repositoriesContributedTo(contributionTypes:[COMMIT,PULL_REQUEST,REPOSITORY]){totalCount}
      }
    }"""
    return gql(q, {"login": USERNAME}, token)["user"]


def fetch_repos(token):
    q = """
    query($login:String!,$cursor:String){
      user(login:$login){
        repositories(first:100, ownerAffiliations:OWNER, after:$cursor,
                     orderBy:{field:STARGAZERS, direction:DESC}){
          totalCount
          pageInfo{hasNextPage endCursor}
          nodes{
            name owner{login} isFork stargazerCount
            defaultBranchRef{ target{ ... on Commit { oid } } }
          }
        }
      }
    }"""
    repos, cursor = [], None
    total = 0
    while True:
        data = gql(q, {"login": USERNAME, "cursor": cursor}, token)["user"]["repositories"]
        total = data["totalCount"]
        repos.extend(data["nodes"])
        if not data["pageInfo"]["hasNextPage"]:
            break
        cursor = data["pageInfo"]["endCursor"]
    if not INCLUDE_FORKS:
        repos = [r for r in repos if not r["isFork"]]
    return repos, total


def fetch_commits(token, created_at):
    q = """
    query($login:String!,$from:DateTime!,$to:DateTime!){
      user(login:$login){
        contributionsCollection(from:$from,to:$to){
          totalCommitContributions
          restrictedContributionsCount
        }
      }
    }"""
    start = datetime.fromisoformat(created_at.replace("Z", "+00:00"))
    now = datetime.now(timezone.utc)
    total = 0
    year = start.year
    while year <= now.year:
        frm = max(start, datetime(year, 1, 1, tzinfo=timezone.utc))
        to = min(now, datetime(year, 12, 31, 23, 59, 59, tzinfo=timezone.utc))
        c = gql(q, {"login": USERNAME, "from": frm.isoformat(), "to": to.isoformat()},
                token)["user"]["contributionsCollection"]
        total += c["totalCommitContributions"] + c["restrictedContributionsCount"]
        year += 1
    return total


def fetch_loc(token, user_id, repos):
    """Additions/deletions authored by you, cached per repo HEAD so reruns are cheap."""
    q = """
    query($owner:String!,$name:String!,$id:ID!,$cursor:String){
      repository(owner:$owner,name:$name){
        defaultBranchRef{ target{ ... on Commit {
          history(first:100, author:{id:$id}, after:$cursor){
            pageInfo{hasNextPage endCursor}
            nodes{ additions deletions }
          }
        }}}
      }
    }"""
    cache_path = Path(CACHE_FILE)
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    cache = json.loads(cache_path.read_text()) if cache_path.exists() else {}

    add = sub = 0
    for r in repos:
        if r["name"] in LOC_EXCLUDE:
            continue
        ref = r.get("defaultBranchRef")
        if not ref or not ref.get("target"):
            continue
        key = f"{r['owner']['login']}/{r['name']}"
        head = ref["target"]["oid"]
        hit = cache.get(key)
        if hit and hit.get("head") == head:
            add += hit["add"]
            sub += hit["sub"]
            continue

        a = s = 0
        cursor = None
        while True:
            d = gql(q, {"owner": r["owner"]["login"], "name": r["name"],
                        "id": user_id, "cursor": cursor}, token)
            ref_ = (d.get("repository") or {}).get("defaultBranchRef") or {}
            hist = (ref_.get("target") or {}).get("history")
            if not hist:
                break
            for n in hist["nodes"]:
                a += n["additions"]
                s += n["deletions"]
            if not hist["pageInfo"]["hasNextPage"]:
                break
            cursor = hist["pageInfo"]["endCursor"]

        cache[key] = {"head": head, "add": a, "sub": s}
        add += a
        sub += s

    cache_path.write_text(json.dumps(cache, indent=1, sort_keys=True))
    return add, sub


