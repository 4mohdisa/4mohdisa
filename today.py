def main():
    ascii_lines = Path(ASCII_FILE).read_text(encoding="utf-8").rstrip("\n").split("\n")

    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("ACCESS_TOKEN")
    if not token:
        print("No GITHUB_TOKEN set — rendering a preview with placeholder numbers.")
        stats = dict(uptime="4 years, 2 months, 11 days", repos=42, contrib=18,
                     stars=210, commits=3120, followers=96, add=520000, sub=180000)
    else:
        profile = fetch_profile(token)
        repos, repo_total = fetch_repos(token)
        add, sub = fetch_loc(token, profile["id"], repos)
        stats = dict(
            uptime=uptime_string(UPTIME_FROM + "T00:00:00Z" if UPTIME_FROM else profile["createdAt"]),
            repos=len(repos) if not INCLUDE_FORKS else repo_total,
            contrib=profile["repositoriesContributedTo"]["totalCount"],
            stars=sum(r["stargazerCount"] for r in repos),
            commits=fetch_commits(token, profile["createdAt"]),
            followers=profile["followers"]["totalCount"],
            add=add, sub=sub,
        )

    fit_canvas(ascii_lines, len(STATIC_ROWS) + 5)
    for name in THEMES:
        Path(f"{name}.svg").write_text(render(name, ascii_lines, stats), encoding="utf-8")
        print(f"wrote {name}.svg")


if __name__ == "__main__":
    sys.exit(main())
