def fit_canvas(ascii_lines, info_rows):
    """Size the card to whatever the ASCII art and the info column actually need."""
    global ASCII_COLS, INFO_X, WIDTH, HEIGHT
    ASCII_COLS = max((len(l) for l in ascii_lines), default=40)
    INFO_X = PAD + ASCII_COLS * CHAR_W + GUTTER
    WIDTH = int(INFO_X + INFO_COLS * 8.05 + PAD)
    HEIGHT = int(TOP + max(len(ascii_lines), info_rows) * LINE_H + PAD)

