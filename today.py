def uptime_string(start_iso):
    start = datetime.fromisoformat(start_iso.replace("Z", "+00:00"))
    now = datetime.now(timezone.utc)
    y = now.year - start.year
    m = now.month - start.month
    d = now.day - start.day
    if d < 0:
        m -= 1
        prev = (now.month - 1) or 12
        days_in = [31, 29 if now.year % 4 == 0 else 28, 31, 30, 31, 30,
                   31, 31, 30, 31, 30, 31][prev - 1]
        d += days_in
    if m < 0:
        y -= 1
        m += 12

    def plural(n, w):
        return f"{n} {w}" + ("" if n == 1 else "s")

    return f"{plural(y,'year')}, {plural(m,'month')}, {plural(d,'day')}"


def commafy(n):
    return f"{n:,}"


# ─────────────────────────────────────────────────────────────────────────────
# SVG
# ─────────────────────────────────────────────────────────────────────────────

_T = {}  # active theme, set by render()


def seg(cls, text):
    extra = ' font-weight="700"' if cls == "prompt" else ""
    return f'<tspan fill="{_T[cls]}"{extra}>{escape(text)}</tspan>'


def row_head(text):
    fill = INFO_COLS - len(text) - 1
    return seg("prompt", text) + seg("rule", " " + "─" * max(fill, 1))


def row_sec(title):
    fill = INFO_COLS - len(title) - 4
    return seg("rule", "─ ") + seg("prompt", title) + seg("rule", " " + "─" * max(fill, 1))


def row_kv(key, value):
    dots = INFO_COLS - len(key) - len(value) - 5
    return (seg("key", "· ") + seg("key", key + ":")
            + seg("dot", " " + "." * max(dots, 1) + " ")
            + seg("val", value))


def half_kv(key, value, width, val_cls="val"):
    dots = width - len(key) - len(value) - 3
    return (seg("key", key + ":") + seg("dot", " " + "." * max(dots, 1) + " ")
            + seg(val_cls, value))


def render(theme_name, ascii_lines, stats):
    t = THEMES[theme_name]
    _T.clear()
    _T.update(t)

    rows = [("head", PROMPT)] + [
        r if r[0] != "kv" else ("kv", r[1], r[2].replace("{UPTIME}", stats["uptime"]))
        for r in STATIC_ROWS
    ]

    body = []
    for r in rows:
        if r[0] == "head":
            body.append(row_head(r[1]))
        elif r[0] == "sec":
            body.append(row_sec(r[1]))
        elif r[0] == "kv":
            body.append(row_kv(r[1], r[2]))
        else:
            body.append(seg("key", "·"))

    # stats block
    body.append(row_sec("GitHub Stats"))
    contributed = " {Contributed: " + str(stats["contrib"]) + "}"
    body.append(
        seg("key", "· ")
        + half_kv("Repos", str(stats["repos"]), 34 - len(contributed))
        + seg("muted", " {Contributed: ") + seg("val", str(stats["contrib"])) + seg("muted", "}")
        + seg("muted", " | ")
        + half_kv("Stars", commafy(stats["stars"]), 23)
    )
    body.append(
        seg("key", "· ")
        + half_kv("Commits", commafy(stats["commits"]), 34)
        + seg("muted", " | ")
        + half_kv("Followers", commafy(stats["followers"]), 23)
    )
    net = commafy(stats["add"] - stats["sub"])
    tail = f" ( {commafy(stats['add'])}++, {commafy(stats['sub'])}-- )"
    body.append(
        seg("key", "· ")
        + half_kv("Lines of Code on GitHub", net, INFO_COLS - 2 - len(tail))
        + seg("muted", " ( ") + seg("add", commafy(stats["add"]) + "++")
        + seg("muted", ", ") + seg("sub", commafy(stats["sub"]) + "--") + seg("muted", " )")
    )

    art = "".join(
        f'<text x="{ASCII_X}" y="{TOP + i * LINE_H:.1f}" fill="url(#artGrad)" xml:space="preserve">'
        f"{escape(line)}</text>"
        for i, line in enumerate(ascii_lines)
    )
    info = "".join(
        f'<text x="{INFO_X:.0f}" y="{TOP + i * LINE_H:.1f}" xml:space="preserve">{line}</text>'
        for i, line in enumerate(body)
    )

    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}" role="img" aria-label="{USERNAME} GitHub profile card">
  <defs>
    <linearGradient id="artGrad" x1="0" y1="0" x2="0.35" y2="1">
      <stop offset="0%" stop-color="{t['art_a']}"/>
      <stop offset="100%" stop-color="{t['art_b']}"/>
    </linearGradient>
  </defs>
  <rect width="{WIDTH}" height="{HEIGHT}" rx="10" fill="{t['outer']}"/>
  <rect x="12" y="12" width="{WIDTH - 24}" height="{HEIGHT - 24}" rx="8" fill="{t['panel']}" stroke="{t['stroke']}"/>
  <g font-family="{FONT}" font-size="{FONT_SIZE}px">
  {art}
  {info}
  </g>
</svg>
"""


